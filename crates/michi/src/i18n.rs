/// The language codes michi has words for.
pub const AVAILABLE: [&str; 2] = ["en", "ja"];

/// The words for `key` in `lang` (`ja`, else English); the key itself when
/// there are none.
pub fn tr(lang: &str, key: &'static str) -> &'static str {
    let table = if lang == "ja" { JA } else { EN };
    let text = table.iter().chain(EN).find(|(k, _)| *k == key).map_or(key, |(_, v)| v);
    mac_spelling(text)
}

/// On macOS the words say Cmd where the table says Ctrl (#61); the spelled
/// copy is made once per string. Elsewhere the table's own text.
fn mac_spelling(text: &'static str) -> &'static str {
    if !cfg!(target_os = "macos") || !text.contains("Ctrl+") {
        return text;
    }
    use std::collections::HashMap;
    use std::sync::{Mutex, OnceLock};
    static SPELLED: OnceLock<Mutex<HashMap<&'static str, &'static str>>> = OnceLock::new();
    let mut seen = SPELLED.get_or_init(Default::default).lock().unwrap();
    seen.entry(text).or_insert_with(|| Box::leak(ito_keys::human_text_for(text, true).into_owned().into_boxed_str()))
}

/// A keymap layer's name in `lang`; the name itself when there are no words.
pub fn tr_layer(lang: &str, layer: &str) -> String {
    lookup(lang, &format!("keylayer.{layer}")).unwrap_or(layer).to_owned()
}

/// A binding's `desc` in `lang`; the desc itself when there are no words.
pub fn tr_desc(lang: &str, desc: &str) -> String {
    lookup(lang, &format!("keydesc.{desc}")).unwrap_or(desc).to_owned()
}

fn lookup(lang: &str, key: &str) -> Option<&'static str> {
    let table = if lang == "ja" { JA } else { EN };
    table.iter().chain(EN).find(|(k, _)| *k == key).map(|(_, v)| *v)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_languages_have_the_same_keys() {
        fn keys(t: &[(&'static str, &'static str)]) -> Vec<&'static str> {
            t.iter().map(|(k, _)| *k).collect()
        }
        assert_eq!(keys(EN), keys(JA));
    }

    /// The first definition of a key wins, so a second one is never read (#96).
    #[test]
    fn no_key_is_defined_twice() {
        for (name, t) in [("EN", EN), ("JA", JA)] {
            let mut seen = std::collections::HashSet::new();
            for (k, _) in t {
                assert!(seen.insert(*k), "{name} defines `{k}` twice");
            }
        }
    }

    /// Every explained git refusal has words in both languages (#108).
    #[test]
    fn every_git_refusal_rule_has_words() {
        for r in michi_core::explain::RULES {
            for key in [r.cause, r.next] {
                for (name, t) in [("EN", EN), ("JA", JA)] {
                    assert!(t.iter().any(|(k, v)| *k == key && !v.is_empty()), "{name} lacks `{key}`");
                }
            }
        }
    }

    #[test]
    fn a_known_refusal_is_told_with_cause_next_step_and_detail() {
        let mut a = crate::app::tests::app();
        let e = michi_core::git::Error::Git("rejected main -> main (fetch first)".into());
        let en = a.git_says(&e);
        assert!(en.starts_with("The remote has commits"), "{en}");
        assert!(en.contains("pull (p)") && en.ends_with("(git said: rejected main -> main (fetch first))"), "{en}");
        a.lang = "ja".into();
        assert!(a.git_says(&e).contains("リモートに"));
        let odd = michi_core::git::Error::Git("fatal: odd".into());
        assert_eq!(a.git_says(&odd), "fatal: odd");
    }

    #[test]
    fn unknown_keys_come_back_as_they_are() {
        assert_eq!(tr("ja", "nope"), "nope");
        assert_eq!(tr("ja", "view.graph"), "樹形図");
        assert_eq!(tr("fr", "view.graph"), "Graph");
    }

    /// The words of both tables follow the one table of terms (#125).
    #[test]
    fn the_tables_use_the_terms_of_the_term_table() {
        let mut bad = Vec::new();
        for (k, v) in JA {
            for (w, t) in michi_core::terms::banned_ja() {
                if v.contains(w) {
                    bad.push(format!("ja `{k}` says `{w}`: the {} is `{}`", t.what, t.ja));
                }
            }
        }
        for (k, v) in EN {
            // `safe.directory` is git's own setting name, not our word for a folder.
            let low = v.to_lowercase().replace("safe.directory", "");
            for (w, t) in michi_core::terms::banned_en() {
                if low.contains(w) {
                    bad.push(format!("en `{k}` says `{w}`: the {} is `{}`", t.what, t.en));
                }
            }
        }
        assert!(
            bad.is_empty(),
            "{}",
            bad.join(
                "
"
            )
        );
    }

    /// GLOSSARY.md shows every term of the table, in both languages.
    #[test]
    fn the_glossary_lists_every_term() {
        let doc = include_str!("../../../GLOSSARY.md");
        for t in michi_core::terms::TERMS {
            let row = doc.lines().find(|l| l.starts_with('|') && l.contains(&format!("| {} |", t.what)));
            let row = row.unwrap_or_else(|| panic!("GLOSSARY.md has no row for {}", t.what));
            let cells: Vec<&str> = row.split('|').map(str::trim).collect();
            assert_eq!(cells.get(2), Some(&t.en), "{}: English", t.what);
            assert_eq!(cells.get(3), Some(&t.ja), "{}: Japanese", t.what);
        }
    }
}
